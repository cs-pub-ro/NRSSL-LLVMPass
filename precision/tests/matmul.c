// C = H * H for the 6x6 Hilbert matrix H[i][j] = 1/(i+j+1). The entries of H
// are already rounded, the products add dot-product rounding on top.

#include "caial.h"

#define N 6

static fp_t h[N][N], c[N][N];

int main(void) {
  for (int i = 0; i < N; i++)
    for (int j = 0; j < N; j++)
      h[i][j] = FP_C(1.0) / (fp_t)(i + j + 1);

  for (int i = 0; i < N; i++) {
    for (int j = 0; j < N; j++) {
      fp_t acc = FP_C(0.0);
      for (int k = 0; k < N; k++)
        acc = acc + h[i][k] * h[k][j];
      c[i][j] = acc;
      CAIAL_TRACE_VALUE("c", i * N + j, acc);
    }
  }
  CAIAL_RESULTS(c, &c[0][0], N * N);

  // exact H*H, computed with fractions
  static const char *exact[N * N] = {
      "1.491388888888888888888889", "0.8571428571428571428571429", "0.6160714285714285714285714",
      "0.4847883597883597883597884", "0.4010912698412698412698413", "0.3426911976911976911976912",
      "0.8571428571428571428571429", "0.5117970521541950113378685", "0.375",
      "0.2986111111111111111111111", "0.2490740740740740740740741", "0.2140782828282828282828283",
      "0.6160714285714285714285714", "0.375", "0.2774220521541950113378685",
      "0.2222222222222222222222222", "0.1861111111111111111111111", "0.1604377104377104377104377",
      "0.4847883597883597883597884", "0.2986111111111111111111111", "0.2222222222222222222222222",
      "0.1786566200554295792391030", "0.15", "0.1295454545454545454545455",
      "0.4010912698412698412698413", "0.2490740740740740740740741", "0.1861111111111111111111111",
      "0.15", "0.1261566200554295792391030", "0.1090909090909090909090909",
      "0.3426911976911976911976912", "0.2140782828282828282828283", "0.1604377104377104377104377",
      "0.1295454545454545454545455", "0.1090909090909090909090909", "0.09442108286534693461100388",
  };
  for (int i = 0; i < N * N; i++)
    CAIAL_EXACT(c, i, exact[i]);
  return 0;
}
